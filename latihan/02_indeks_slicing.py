# Input: Enam nilai mahasiswa.
nilai = [75, 80, 65, 90, 88, 70]

# Proses: Mengakses elemen dengan indeks dan slicing.
# Output: Menampilkan elemen yang diminta.
print(f"Elemen pertama = {nilai[0]}")
print(f"Elemen terakhir = {nilai[-1]}")
print(f"Tiga elemen awal = {nilai[:3]}")
print(f"Elemen indeks 1 sampai 3 = {nilai[1:4]}")
